#!/usr/bin/env node
/* global process */
// PreToolUse backstop: ask before editing generated data, workflows, or release
// and hook files, so an agent cannot silently hand-edit them. The human decides;
// CODEOWNERS is the durable gate.
import { readFileSync } from "node:fs";

let file;
try {
  file = JSON.parse(readFileSync(0, "utf8"))?.tool_input?.file_path || "";
} catch {
  process.exit(0);
}
const rel = file.replace(/^.*\/backblaze-labs\/website\//, "");
const protectedPatterns = [
  /^src\/data\/(github-stats|links|previews|preview-sources|labs\.discovered)\.json$/,
  /^\.github\/workflows\//,
  /^\.changie\.yaml$/,
  /^(RELEASE|CHANGELOG)\.md$/,
  /^\.claude\/hooks\//,
];
if (protectedPatterns.some((p) => p.test(rel))) {
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "ask",
        permissionDecisionReason: `${rel} is generated or policy-critical. Generated data is regenerated by the sync scripts, and workflows must keep the Dependabot CI guard. Confirm you mean to edit it by hand.`,
      },
    }),
  );
}
process.exit(0);
